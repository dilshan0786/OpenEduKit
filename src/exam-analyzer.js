/**
 * OpenEduKit.js - Exam Analyzer & Reporter
 * 
 * Zero-Base Developer Explanations:
 * - What is a Map/Reduce? Map transforms arrays, and Reduce collapses arrays into single values/objects.
 *   Here, we scan student answers one-by-one to count match states (Correct vs Incorrect).
 * - Division & Math: Percentages are calculated as `(correct / total) * 100`. We use `.toFixed(1)`
 *   to avoid JavaScript float problems (like `33.3333333333%`).
 */

(function (global) {
  'use strict';

  /**
   * Evaluates student response vector against correct answer keys.
   * @param {Object[]} questions Original question set containing correctAnswerIndex
   * @param {Object[]} responses Student responses (array of { questionId, selectedAnswerIndex })
   * @returns {Object} Analytical report object
   */
  function analyzeExam(questions, responses) {
    const totalQuestions = questions.length;
    let correct = 0;
    let incorrect = 0;
    let unattempted = 0;

    // Create a lookup map for faster response matching
    // Zero-base Explanation: An object lookup runs in O(1) time complexity.
    // Instead of doing a nested loop for every question, we build a dictionary first.
    const responseLookup = {};
    responses.forEach(resp => {
      responseLookup[resp.questionId] = resp.selectedAnswerIndex;
    });

    const breakdown = questions.map((q) => {
      const selected = responseLookup[q.id];
      const isAttempted = selected !== null && selected !== undefined;
      const isCorrect = isAttempted && selected === q.correctAnswerIndex;

      if (!isAttempted) {
        unattempted++;
      } else if (isCorrect) {
        correct++;
      } else {
        incorrect++;
      }

      return {
        questionId: q.id,
        questionText: q.questionText,
        correctAnswerIndex: q.correctAnswerIndex,
        selectedAnswerIndex: selected,
        status: !isAttempted ? 'unattempted' : (isCorrect ? 'correct' : 'incorrect')
      };
    });

    const percentage = totalQuestions > 0 ? parseFloat(((correct / totalQuestions) * 100).toFixed(1)) : 0;

    return {
      totalQuestions,
      correct,
      incorrect,
      unattempted,
      percentage,
      breakdown
    };
  }

  /**
   * Generates a clean HTML scorecard and injects it into a container.
   * @param {string} containerId DOM target
   * @param {Object} report The object generated by `analyzeExam`
   */
  function renderReportHTML(containerId, report) {
    const container = document.getElementById(containerId);
    if (!container) {
      console.error(`OpenEduKit Analyzer: Target container "${containerId}" not found.`);
      return;
    }

    container.innerHTML = '';

    const card = document.createElement('div');
    card.className = 'report-card';

    // Header Title
    const title = document.createElement('h2');
    title.className = 'report-title';
    title.textContent = "Exam Analysis Report";
    card.appendChild(title);

    // Stats Grid
    const grid = document.createElement('div');
    grid.className = 'report-stats-grid';

    const metrics = [
      { value: `${report.correct} / ${report.totalQuestions}`, label: "Correct", class: "correct" },
      { value: `${report.incorrect}`, label: "Incorrect", class: "incorrect" },
      { value: `${report.percentage}%`, label: "Percentage Score", class: "score" }
    ];

    metrics.forEach(m => {
      const box = document.createElement('div');
      box.className = 'report-stat-box';

      const val = document.createElement('div');
      val.className = `report-stat-val ${m.class}`;
      val.textContent = m.value;

      const lbl = document.createElement('div');
      lbl.className = 'report-stat-lbl';
      lbl.textContent = m.label;

      box.appendChild(val);
      box.appendChild(lbl);
      grid.appendChild(box);
    });

    card.appendChild(grid);

    // Question Breakdown Table / Details
    const detailsHeader = document.createElement('h3');
    detailsHeader.style.margin = '25px 0 15px 0';
    detailsHeader.style.fontSize = '16px';
    detailsHeader.textContent = "Question-by-Question breakdown:";
    card.appendChild(detailsHeader);

    const listContainer = document.createElement('div');
    listContainer.style.display = 'flex';
    listContainer.style.flexDirection = 'column';
    listContainer.style.gap = '10px';

    report.breakdown.forEach((item, index) => {
      const row = document.createElement('div');
      row.style.padding = '12px 16px';
      row.style.border = '1px solid var(--border-color)';
      row.style.borderRadius = 'var(--radius-sm)';
      row.style.display = 'flex';
      row.style.justifyContent = 'space-between';
      row.style.alignItems = 'center';
      row.style.fontSize = '14px';

      // Status indicator coloring
      let statusText = "Unattempted";
      let statusColor = "var(--text-secondary)";
      let rowBg = "#fff";

      if (item.status === 'correct') {
        statusText = "Correct";
        statusColor = "var(--success)";
        rowBg = "#f0fdf4";
      } else if (item.status === 'incorrect') {
        statusText = "Incorrect";
        statusColor = "var(--error)";
        rowBg = "#fef2f2";
      }

      row.style.backgroundColor = rowBg;

      const textSection = document.createElement('div');
      const numSpan = document.createElement('strong');
      numSpan.textContent = `Q${index + 1}: `;
      const textSpan = document.createElement('span');
      textSpan.textContent = item.questionText.substring(0, 50) + (item.questionText.length > 50 ? '...' : '');

      textSection.appendChild(numSpan);
      textSection.appendChild(textSpan);

      const statusBadge = document.createElement('span');
      statusBadge.style.fontWeight = '700';
      statusBadge.style.color = statusColor;
      statusBadge.textContent = statusText;

      row.appendChild(textSection);
      row.appendChild(statusBadge);
      listContainer.appendChild(row);
    });

    card.appendChild(listContainer);
    container.appendChild(card);
  }

  // Export functions to window or node environment
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = { analyzeExam, renderReportHTML };
  } else {
    global.OpenEduKit = global.OpenEduKit || {};
    global.OpenEduKit.analyzeExam = analyzeExam;
    global.OpenEduKit.renderReportHTML = renderReportHTML;
  }

})(typeof window !== 'undefined' ? window : this);
